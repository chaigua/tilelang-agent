# does not pull in plain (non-@tilelang.jit) helpers imported from a sibling
# module.  ``_argreduce_kernel`` calls ``align_up(N, DEFAULT_ALIGNMENT)`` to
# derive ``N_padded``, so the alignment must not be re-derived anywhere else.
def align_up(n: int, alignment: int) -> int:
    """Round *n* up to the nearest multiple of *alignment*.

    Args:
        n: Value to align.
        alignment: Alignment boundary (must be positive).

    Returns:
        Smallest multiple of *alignment* that is >= *n*.

    Raises:
        ValueError: If *alignment* is not positive.
    """
    if alignment <= 0:
        raise ValueError(f"alignment must be positive, got {alignment}")
    return ((n + alignment - 1) // alignment) * alignment


