# does not pull in plain (non-@tilelang.jit) helpers imported from a sibling
# module.  `_max_pool2d_kernel` calls `pool_output_dim` for both output
# extents, including the ceil_mode correction, so the length formula must not
# be re-derived anywhere else.
def pool_output_dim(
    input_size: int,
    kernel_size: int,
    stride: int,
    padding: int,
    ceil_mode: bool,
    dilation: int = 1,
) -> int:
    effective_kernel = dilation * (kernel_size - 1) + 1
    if ceil_mode:
        out = (input_size + 2 * padding - effective_kernel + stride - 1) // stride + 1
    else:
        out = (input_size + 2 * padding - effective_kernel) // stride + 1

    if ceil_mode and out > 0 and (out - 1) * stride >= input_size + padding:
        out -= 1

    return max(out, 0)


